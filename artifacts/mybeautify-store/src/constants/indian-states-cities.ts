/**
 * Returns alphabetically sorted city list for the chosen state, with 'Other' as final option.
 */
export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const found = Object.keys(INDIAN_STATE_CITIES).find(
    (s) => s.toLowerCase() === stateName.trim().toLowerCase()
  );
  const cities = found ? [...INDIAN_STATE_CITIES[found]] : [];
  cities.sort((a, b) => a.localeCompare(b));
  cities.push('Other');
  return cities;
}

/**
 * Normalizes state name to official list if matched case-insensitively
 */
export function findMatchingState(inputState?: string): string {
  if (!inputState) return '';
  const match = INDIAN_STATES_AND_UTS.find(
    (s) => s.toLowerCase() === inputState.trim().toLowerCase()
  );
  return match || inputState;
}

